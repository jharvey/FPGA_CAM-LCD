def text_png(lines, path):
    import matplotlib
    from PIL import Image, ImageDraw, ImageFont
    ttf = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono.ttf")
    font = ImageFont.truetype(ttf, 15)
    cw, chh = font.getlength("M"), 19
    img = Image.new("RGB", (int(cw * max(len(s) for s in lines)) + 24, chh * len(lines) + 20), (16, 20, 26))
    d = ImageDraw.Draw(img)
    for i, s in enumerate(lines):
        for j, c in enumerate(s):                       # one cell per character keeps the frame lines straight
            if c != " ":
                col = (120, 200, 255) if c in "█●◆▲" else ((95, 105, 120) if c in "─│┌┐└┘├┤┬┴┼░·" else (225, 230, 235))
                d.text((12 + j * cw, 10 + i * chh), c, font=font, fill=col)
    img.save(path)


