def run_scenes():
    out = []
    for name, title, secs, cmds, note in SCENES:
        dash, sim = fcl_dash.snapshot(secs, cmds)
        t = dict(fcl_hub.last)
        frame = dash.render()
        text_png(frame, os.path.join(OUT, "dash_%s.png" % name))
        fcl_osd.render(t, sim.state["osd"]).save(os.path.join(OUT, "lcd_%s.png" % name))
        out.append((name, title, note, frame, sim.hub.name, t))
        sim.close()
        print("scene", name, "done")
    return out


def stream_excerpt():
    import fcl_sim
    sim = fcl_sim.Sim()
    lines = []
    script = {1.0: "servo 2 1800", 1.2: "overlay dot batt heading", 1.4: "wifi HomeNet secretpass", 5.6: "zero", 5.8: "bogus"}
    keep = []
    while sim.t < 6.0:
        for k in list(script):
            if sim.t >= k:
                keep.append("> " + script.pop(k))
                sim.command(keep[-1][2:])
        for line in sim.step():
            if line.startswith("$T"):
                lines.append(line)
            else:
                keep.append(line)
    sim.close()
    return lines[:2] + ["..."] + keep[:14]


