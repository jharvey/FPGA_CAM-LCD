#!/usr/bin/env python3
"""Build the bridge-only bitstream (fcl_bridge_top.v) with Yosys, nextpnr-ecp5 and ecppack.

    python fpga/bridge/build_bridge.py            -> fpga/bridge/build/fcl_bridge.bit
Uses the tools on the PATH or Icestudio's oss-cad-suite.  Pins come from firmware/hub/fcl_hub_pins.lpf (generated
from the routed board) plus the 25 MHz clock on G2.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "osd"))
from test_osd import tool, env        # noqa: E402

build = os.path.join(HERE, "build")
os.makedirs(build, exist_ok=True)
USED = ("i2c_scl i2c_sda imu_int1 imu_int2 mag_drdy baro_int tof_int tof_xshut adc_cnv adc_din adc_sck adc_sdo btn_pwr_n "
        "btn1_n btn2_n led0 led1 srv_pwm1 srv_pwm2 srv_pwm3 srv_pwm4 srv_pwm5 srv_pwm6 esp_rx esp_tx shutdown").split()
PULLUP = ("btn_pwr_n", "btn1_n", "btn2_n", "esp_rx")
src = open(os.path.join(HERE, "..", "..", "firmware", "hub", "fcl_hub_pins.lpf")).read()
lpf = ['# generated by build_bridge.py from firmware/hub/fcl_hub_pins.lpf', 'BLOCK RESETPATHS;', 'BLOCK ASYNCPATHS;',
       'LOCATE COMP "clk_25mhz" SITE "G2";', 'IOBUF PORT "clk_25mhz" PULLMODE=NONE IO_TYPE=LVCMOS33;',
       'FREQUENCY PORT "clk_25mhz" 25 MHZ;']
for name in USED:
    m = re.search(r'LOCATE COMP "%s" SITE "(\w+)";' % name, src)
    assert m, name
    lpf.append('LOCATE COMP "%s" SITE "%s";' % (name, m.group(1)))
    lpf.append('IOBUF PORT "%s" PULLMODE=%s IO_TYPE=LVCMOS33 DRIVE=4;' % (name, "UP" if name in PULLUP else "NONE"))
open(os.path.join(build, "fcl_bridge_top.lpf"), "w").write("\n".join(lpf) + "\n")


def run(cmd, log):
    r = subprocess.run(cmd, cwd=build, env=env(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    open(os.path.join(build, log), "wb").write(r.stdout)
    if r.returncode:
        print(r.stdout.decode(errors="replace")[-3000:])
        raise SystemExit("%s failed, see build/%s" % (os.path.basename(cmd[0]), log))
    return r.stdout.decode(errors="replace")


v = [os.path.join(HERE, f).replace("\\", "/") for f in ("fcl_bridge_top.v", "fcl_bridge.v")]
run([tool("yosys"), "-p", "read_verilog %s; synth_ecp5 -top fcl_bridge_top -json fcl_bridge.json" % " ".join(v)], "yosys.log")
out = run([tool("nextpnr-ecp5"), "--85k", "--package", "CABGA381", "--speed", "6", "--json", "fcl_bridge.json",
           "--lpf", "fcl_bridge_top.lpf", "--textcfg", "fcl_bridge.config", "--seed", "1"], "nextpnr.log")
run([tool("ecppack"), "--compress", "fcl_bridge.config", "fcl_bridge.bit"], "ecppack.log")
fmax = re.findall(r"Max frequency for clock\s+'[^']+': ([\d.]+) MHz \((PASS|FAIL) at ([\d.]+) MHz\)", out)
util = re.findall(r"(TRELLIS_COMB|TRELLIS_FF|DP16KD|TRELLIS_IO):\s+(\d+)/\s*(\d+)\s+(\d+)%", out)
for name, used, total, pct in util:
    print("%-13s %6s / %s (%s %%)" % (name, used, total, pct))
if fmax:
    print("clock: %s MHz possible, %s at %s MHz" % fmax[-1])
print("wrote", os.path.join(build, "fcl_bridge.bit"), os.path.getsize(os.path.join(build, "fcl_bridge.bit")), "bytes")
