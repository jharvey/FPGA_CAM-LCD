#!/usr/bin/env python3
"""Build the full FPGA design: camera to TFT + LCD overlay + sensor bridge, in one bitstream.

    python fpga/full/build_full.py [--out DIR]      -> fpga/full/build/fcl_full.bit

Steps: Icestudio's code generator on fpga/CameraToTFTSobel_FCL.ice (fpga/build.py --gen-only) gives main.v; this
script writes fcl_cam.v (the same module with readable port names) and fcl_top.lpf (pins from the .ice file and from
firmware/hub/fcl_hub_pins.lpf), then Yosys, nextpnr-ecp5 and ecppack build fcl_top.v with the bridge and the overlay.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FPGA = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(FPGA, "osd"))
from test_osd import tool, env        # noqa: E402

ICE = os.path.join(FPGA, "CameraToTFTSobel_FCL.ice")
HUB_PINS = ("i2c_scl i2c_sda imu_int1 imu_int2 mag_drdy baro_int tof_int tof_xshut adc_cnv adc_din adc_sck adc_sdo btn_pwr_n "
            "btn1_n btn2_n led0 led1 srv_pwm1 srv_pwm2 srv_pwm3 srv_pwm4 srv_pwm5 srv_pwm6 esp_rx esp_tx shutdown").split()
PULLUP = ("btn_pwr_n", "btn1_n", "btn2_n", "esp_rx")
INTERNAL = ("rst_n", "switch", "inc_threshold", "dec_threshold")       # camera inputs driven inside fcl_top
RENAME = {"clk": "clk_25mhz", "debug_OUT": "pix_clk_out"}


def ice_ports():
    """[(direction, generated name, readable name, width or None, [balls, most significant first])]"""
    project = json.load(open(ICE, encoding="utf-8"))
    out = []
    for b in project["design"]["graph"]["blocks"]:
        if b["type"] in ("basic.input", "basic.output"):
            d = b["data"]
            gen = "v" + (hashlib.sha1(b["id"].encode()).hexdigest() if "-" in b["id"] else b["id"])[:6]
            out.append((b["type"][6:], gen, re.sub(r"\W", "_", d["name"]), len(d["pins"]) if d.get("range") else None,
                        [p["value"] for p in d["pins"]]))
    return out


def write_sources(build):
    ports = ice_ports()
    main_v = open(os.path.join(build, "main.v"), encoding="utf-8").read()
    v = ["// generated by build_full.py: module main (Icestudio's output) with the port names of the .ice file",
         "module fcl_cam ("]
    v.append(",\n".join("    %s wire %s%s" % (d, "[%d:0] " % (w - 1) if w else "", n) for d, g, n, w, _ in ports))
    v.append(");\n    main m (")
    for d, g, n, w, _ in ports:
        assert re.search(r"\b%s\b" % g, main_v), "port %s (%s) is not in the generated main.v" % (n, g)
    v.append(",\n".join("        .%s(%s)" % (g, n) for d, g, n, w, _ in ports))
    v.append("    );\nendmodule")
    open(os.path.join(build, "fcl_cam.v"), "w", newline="\n").write("\n".join(v) + "\n")

    pull = dict(re.findall(r'IOBUF\s+PORT "([^"]+)" PULLMODE=(\w+)', open(os.path.join(build, "main.lpf"), encoding="utf-8").read()))
    lpf = ["# generated by build_full.py from %s and firmware/hub/fcl_hub_pins.lpf" % os.path.basename(ICE),
           "BLOCK RESETPATHS;", "BLOCK ASYNCPATHS;", 'FREQUENCY PORT "clk_25mhz" 25 MHZ;', 'FREQUENCY PORT "cmos_pclk" 24 MHZ;']
    used = {}

    def pin(name, ball, mode):
        assert ball not in used, "ball %s wanted by %s and %s" % (ball, used[ball], name)
        used[ball] = name
        lpf.append('LOCATE COMP "%s" SITE "%s";' % (name, ball))
        lpf.append('IOBUF PORT "%s" PULLMODE=%s IO_TYPE=LVCMOS33 DRIVE=4;' % (name, mode))

    for d, g, n, w, balls in ports:
        if n in INTERNAL:
            continue
        for i, ball in enumerate(balls):
            bit = len(balls) - 1 - i
            mode = pull.get("%s[%d]" % (g, bit) if w else g, "NONE")
            m = re.match(r"LCD_([RGB])(\d)$", n)
            if m:
                pin("LCD_%s[%s]" % (m.group(1), m.group(2)), ball, mode)
            elif n == "led":
                if bit >= 2:
                    pin("cam_led[%d]" % (bit - 2), ball, mode)            # led[1:0] are LED0 / LED1: the bridge's
            else:
                pin("%s[%d]" % (RENAME.get(n, n), bit) if w else RENAME.get(n, n), ball, mode)
    hub = open(os.path.join(FPGA, "..", "firmware", "hub", "fcl_hub_pins.lpf")).read()
    for name in HUB_PINS:
        m = re.search(r'LOCATE COMP "%s" SITE "(\w+)";' % name, hub)
        assert m, name
        pin(name, m.group(1), "UP" if name in PULLUP else "NONE")
    open(os.path.join(build, "fcl_top.lpf"), "w", newline="\n").write("\n".join(lpf) + "\n")
    return len(used)


def run(build, cmd, log):
    r = subprocess.run(cmd, cwd=build, env=env(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    open(os.path.join(build, log), "wb").write(r.stdout)
    if r.returncode:
        print(r.stdout.decode(errors="replace")[-3000:])
        raise SystemExit("%s failed, see %s" % (os.path.basename(cmd[0]), os.path.join(build, log)))
    return r.stdout.decode(errors="replace")


def main():
    build = os.path.join(HERE, "build")
    if "--out" in sys.argv:
        build = os.path.abspath(sys.argv[sys.argv.index("--out") + 1])
    os.makedirs(build, exist_ok=True)
    r = subprocess.run([sys.executable, os.path.join(FPGA, "build.py"), "--gen-only", "--out", build],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode:
        raise SystemExit("code generation failed:\n" + r.stdout.decode(errors="replace")[-2000:])
    shutil.copy(os.path.join(FPGA, "osd", "font16x32.hex"), build)
    pins = write_sources(build)
    src = [os.path.join(HERE, "fcl_top.v"), os.path.join(FPGA, "bridge", "fcl_bridge.v"), os.path.join(FPGA, "osd", "fcl_osd.v"),
           os.path.join(FPGA, "osd", "fcl_osd_stream.v")]
    files = " ".join(["main.v", "fcl_cam.v"] + [s.replace("\\", "/") for s in src])
    run(build, [tool("yosys"), "-p", "read_verilog %s; synth_ecp5 -top fcl_top -json fcl_full.json" % files], "yosys.log")
    out = run(build, [tool("nextpnr-ecp5"), "--85k", "--package", "CABGA381", "--speed", "6", "--json", "fcl_full.json",
                      "--lpf", "fcl_top.lpf", "--textcfg", "fcl_full.config", "--seed", "1", "--timing-allow-fail"], "nextpnr.log")
    run(build, [tool("ecppack"), "--compress", "fcl_full.config", "fcl_full.bit"], "ecppack.log")
    print("pins placed: %d" % pins)
    for name, used, total, pct in re.findall(r"(TRELLIS_COMB|TRELLIS_FF|DP16KD|TRELLIS_IO):\s+(\d+)/\s*(\d+)\s+(\d+)%", out):
        print("%-13s %6s / %s (%s %%)" % (name, used, total, pct))
    last = {}
    for clk, mhz, res, want in re.findall(r"Max frequency for clock\s+'([^']+)': ([\d.]+) MHz \((PASS|FAIL) at ([\d.]+) MHz\)", out):
        last[clk] = (mhz, res, want)
    for clk, (mhz, res, want) in sorted(last.items()):
        note = ""
        if "pix_clk" in clk:                             # nextpnr does not follow this PLL: the pixel clock is 18 MHz
            res, want, note = ("PASS" if float(mhz) >= 18.0 else "FAIL"), "18.00", "  (LCD pixel clock)"
        elif "w25" in clk:
            note = "  (SDRAM clock of the camera design)"
        elif "xclk" in clk or "clk_25mhz" in clk:
            note = "  (25 MHz board clock: bridge, overlay text memory, camera set-up)"
        last[clk] = (mhz, res, want)
        print("clock %-40s %7s MHz possible, %s at %s MHz%s" % (clk[-40:], mhz, res, want, note))
    bit = os.path.join(build, "fcl_full.bit")
    print("wrote", bit, os.path.getsize(bit), "bytes")
    return 1 if any(v[1] == "FAIL" for v in last.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
